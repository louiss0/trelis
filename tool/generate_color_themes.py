"""Generate lib/src/color_theme_palettes.g.dart from tool/generate_theme_atlas.py.

Run: python tool/generate_color_themes.py
"""

import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'tool' / 'generate_theme_atlas.py'
DEST = ROOT / 'lib' / 'src' / 'color_theme_palettes.g.dart'


def parse_specs(path: Path):
    text = path.read_text(encoding='utf-8')
    tree = ast.parse(text)
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id == 'SPECS':
                    return ast.literal_eval(node.value)
    raise ValueError('SPECS not found in generate_theme_atlas.py')


def to_camel_case(slug: str) -> str:
    parts = slug.split('-')
    return parts[0] + ''.join(part.capitalize() for part in parts[1:])


def hex_to_rgb(value: str):
    value = value.lstrip('#')
    if len(value) != 6:
        raise ValueError(f'Expected six-digit hex, got {value!r}')
    return tuple(int(value[i:i + 2], 16) for i in (0, 2, 4))


def dart_palette_final(name: str, palette):
    (
        _page,
        terminal,
        text,
        muted,
        accent,
        selected,
        success,
        error,
        rule,
    ) = palette
    rgb = {k: hex_to_rgb(v) for k, v in {
        'foreground': text,
        'background': terminal,
        'muted': muted,
        'accent': accent,
        'selectionForeground': selected,
        'selectionBackground': accent,
        'success': success,
        'warning': accent,
        'error': error,
        'border': rule,
    }.items()}
    fields = '\n'.join(
        f'    {role}: TerminalColor.rgb({r}, {g}, {b}),'
        for role, (r, g, b) in rgb.items()
    )
    return f'''  static final {name} = ColorTheme(
{fields}
  );'''


def generate():
    specs = parse_specs(SOURCE)
    consts = [dart_palette_final(to_camel_case(slug), palette) for (
        _name,
        slug,
        _mode,
        _description,
        palette,
    ) in specs]

    dest_text = f'''// Generated by tool/generate_color_themes.py from tool/generate_theme_atlas.py.
// Do not edit by hand.

part of 'color_theme.dart';

/// Built-in immutable colour palettes.
abstract final class ColorThemes {{
  /// Terminal-native default. No role forces a dark or light surface.
  static const terminalDefault = ColorTheme(
    foreground: TerminalColor.terminalDefault(),
    background: TerminalColor.terminalDefault(),
    muted: TerminalColor.terminalDefault(),
    accent: TerminalColor.terminalDefault(),
    selectionForeground: TerminalColor.terminalDefault(),
    selectionBackground: TerminalColor.terminalDefault(),
    success: TerminalColor.terminalDefault(),
    warning: TerminalColor.terminalDefault(),
    error: TerminalColor.terminalDefault(),
    border: TerminalColor.terminalDefault(),
  );

{chr(10).join(consts)}
}}
'''
    DEST.write_text(dest_text, encoding='utf-8')
    print(f'Generated {len(consts)} palettes in {DEST}')


if __name__ == '__main__':
    generate()
