"""Generate the internal Ascii ink-blue adaptive palette defaults.

Run: python tool/generate_ascii_ink_blue_palettes.py
Check only: python tool/generate_ascii_ink_blue_palettes.py --check
"""

import json
import sys
from pathlib import Path

from lf_output import write_lf

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'tool' / 'ascii_ink_blue_palettes.json'
DEST = ROOT / 'lib' / 'src' / 'ascii_ink_blue_palettes.g.dart'

ROLES = (
    'foreground',
    'background',
    'muted',
    'accent',
    'selectionForeground',
    'selectionBackground',
    'success',
    'warning',
    'error',
    'border',
)


def rgb(value):
    digits = value.lstrip('#')
    if len(digits) != 6:
        raise ValueError(f'Expected six-digit hex, got {value!r}')
    return tuple(int(digits[i:i + 2], 16) for i in (0, 2, 4))


def color_dart(value):
    if value == 'terminalDefault':
        return 'const TerminalColor.terminalDefault()'
    red, green, blue = rgb(value)
    return f'TerminalColor.rgb({red}, {green}, {blue})'


def palette_dart(name, spec):
    missing = [role for role in ROLES if role not in spec]
    if missing:
        raise ValueError(f'{name} is missing roles: {missing}')
    fields = '\n'.join(
        f'    {role}: {color_dart(spec[role])},' for role in ROLES
    )
    return f'  static final ColorTheme {name} = ColorTheme(\n{fields}\n  );'


def reference_dart(name, value):
    red, green, blue = rgb(value)
    return (
        f'  static const ({{int red, int green, int blue}}) {name}Reference = (\n'
        f'    red: {red},\n'
        f'    green: {green},\n'
        f'    blue: {blue},\n'
        f'  );\n'
        f'  static const String {name}ReferenceHex = {value!r};'
    )


def generate():
    spec = json.loads(SOURCE.read_text(encoding='utf-8'))
    references = spec['referenceBackgrounds']
    palettes = spec['palettes']
    blocks = [
        palette_dart('light', palettes['light']),
        palette_dart('dark', palettes['dark']),
        reference_dart('light', references['light']),
        reference_dart('dark', references['dark']),
    ]
    blocks_text = '\n\n'.join(blocks)
    text = f'''// Generated by tool/generate_ascii_ink_blue_palettes.py from
// tool/ascii_ink_blue_palettes.json. Do not edit by hand.
part of 'ascii_ink_blue_theme.dart';

/// Authored Ascii defaults for the Atelier warm-ink family.
///
/// The reference backgrounds are documentation and contrast-test inputs, not
/// painted terminal surfaces. Palette backgrounds stay terminal-native.
final class AsciiAdaptivePalettes {{
{blocks_text}
}}
'''
    if '--check' in sys.argv[1:]:
        if DEST.read_bytes() != text.encode('utf-8'):
            raise SystemExit(f'{DEST} is stale; regenerate it.')
        print(f'{DEST} is current')
        return
    write_lf(DEST, text)
    print(f'Generated {DEST}')


if __name__ == '__main__':
    generate()
